/**
 * Write the React.js SDK's `.env.local` from profile values.
 *
 * The chat-component reads runtime endpoints from `import.meta.env` via
 * `src/utils/runtimeHostConfig.ts`, which Vite populates from the
 * `.env.local` file at the repo root. The legacy approach of patching
 * a tracked top-level `config.ts` was a no-op against runtime — that
 * file isn't on the runtime path any more — and committed customer
 * endpoints into source, which violates the product-code policy
 * (.claude/rules/product-code-policy.md in the BDSM workspace).
 *
 * Keys written here match what `runtimeHostConfig.buildRuntimeHostConfig`
 * reads. Pairs with ethora-chat-component PR #70 which wires
 * `src/App.tsx` defaults to those env vars.
 */
function patchReactConfig(outputDir: string, profile: Profile): string[] {
  const e = profile.endpoints;

  const lines = [
    `# Generated by @ethora/setup — profile: ${profile.name}`,
    `# Consumed by Vite at dev/build time; surfaces through src/config.ts.`,
    `# This file is gitignored — never commit real endpoints / app IDs.`,
    `VITE_APP_ID=${profile.appId}`,
    `VITE_API=${e.apiUrl}`,
    `VITE_DOMAIN_NAME=${profile.domainName || ""}`,
    `VITE_WEB_DOMAIN=${profile.webAppUrl ? profile.webAppUrl.replace(/^https?:\/\//, "").replace(/\/.*$/, "") : ""}`,
    `VITE_XMPP_HOST=${e.xmppHost}`,
    `VITE_XMPP_SERVICE=${e.xmppConference}`,
    `VITE_APP_XMPP_SERVICE=${e.xmppWebSocket}`,
    ``,
  ];

  const envPath = join(outputDir, ".env.local");
  writeFileSync(envPath, lines.join("\n"));
  return [".env.local (Vite env: VITE_API + VITE_APP_ID + VITE_XMPP_*)"];
}

export function generateConfig(
  profile: Profile,
  target: SdkTarget,
  outputDir: string
): string[] {
  // Android: patch sample app's build.gradle.kts or legacy SDK source files
  if (target === "android" && isAndroidSample(outputDir)) {
    return patchSampleApp(outputDir, profile);
  }
  if (target === "android" && isAndroidSdk(outputDir)) {
    return patchAppConfig(outputDir, profile);
  }

  // Swift: patch SDKPlayground (ethora-sample-swift) if detected; otherwise
  // fall through to the standalone EthoraConfig.swift generator below.
  if (target === "swift" && isSwiftSample(outputDir)) {
    return patchSwiftSample(outputDir, profile);
  }

  // React.js: patch config.ts if SDK detected
  if (target === "reactjs" && existsSync(join(outputDir, "config.ts"))) {
    return patchReactConfig(outputDir, profile);
  }

  let files: GeneratedFile[];

  switch (target) {
    case "android":
      files = generateAndroidFallback(profile);
      break;
    case "swift":
      files = [generateSwiftConfig(profile)];
      break;
    case "reactjs":
    case "reactnative":
      files = [generateEnvFile(profile)];
      break;
    case "wordpress":
      files = [generateWordPressConfig(profile)];
      break;
  }

  const written: string[] = [];
  for (const file of files) {
    const fullPath = join(outputDir, file.path);
    const dir = fullPath.substring(0, fullPath.lastIndexOf("/"));
    if (dir && !existsSync(dir)) {
      mkdirSync(dir, { recursive: true });
    }
    writeFileSync(fullPath, file.content);
    written.push(file.description);
  }

  return written;
}

export function showConfigPreview(profile: Profile, target: SdkTarget): string {
  const e = profile.endpoints;
  switch (target) {
    case "android": {
      const testUser = profile.testUsers?.[0];
      const userLines = testUser
        ? [
            `//   ETHORA_USER_EMAIL     = ${testUser.email}`,
            `//   ETHORA_USER_PASSWORD  = ${testUser.password}`,
            testUser.jwt
              ? `//   ETHORA_USER_JWT       = <${testUser.username}'s JWT, ${testUser.jwt.length} chars>`
              : `//   ETHORA_USER_JWT       = (empty — sample will default to email/password login)`,
          ]
        : [`//   (no test user — Setup tab will open with blank email/password)`];
      return [
        `// Android sample (ethora-sample-android): will write .env at the repo root, consumed by app/build.gradle.kts at build time.`,
        `// Android SDK only (ethora-sdk-android): will patch AppConfig.kt defaults.`,
        `//   ETHORA_APP_ID         = ${profile.appId}`,
        `//   ETHORA_APP_TOKEN      = ${profile.appToken ? "<app JWT>" : "(empty)"}`,
        `//   ETHORA_API_BASE_URL   = ${e.apiUrl}`,
        `//   ETHORA_XMPP_SERVER_URL= ${e.xmppWebSocket}`,
        `//   ETHORA_XMPP_HOST      = ${e.xmppHost}`,
        `//   ETHORA_XMPP_CONFERENCE= ${e.xmppConference}`,
        ...userLines,
      ].join("\n");
    }
    case "reactjs": {
      const webDomain = profile.webAppUrl
        ? profile.webAppUrl.replace(/^https?:\/\//, "").replace(/\/.*$/, "")
        : "";
      return [
        `// React.js demo (ethora-chat-component): will write .env.local at the repo root, consumed by Vite.`,
        `//   VITE_APP_ID           = ${profile.appId}`,
        `//   VITE_API              = ${e.apiUrl}`,
        `//   VITE_DOMAIN_NAME      = ${profile.domainName || ""}`,
        `//   VITE_WEB_DOMAIN       = ${webDomain}`,
        `//   VITE_XMPP_HOST        = ${e.xmppHost}`,
        `//   VITE_XMPP_SERVICE     = ${e.xmppConference}`,
        `//   VITE_APP_XMPP_SERVICE = ${e.xmppWebSocket}`,
      ].join("\n");
    }
    case "swift": {
      const testUser = profile.testUsers?.[0];
      const userLine = testUser
        ? `//   email / password = ${testUser.email} / ${testUser.password}${testUser.jwt ? "  (+ JWT)" : ""}`
        : `//   (no test user — developer will fill email/password in the SDKPlayground Setup tab)`;
      return [
        `// Swift sample (ethora-sample-swift): will patch SDKPlayground/PlaygroundSession.swift @Published defaults so the Setup tab opens pre-filled with:`,
        `// Swift SDK only (ethora-sdk-swift): will write a standalone EthoraConfig.swift file instead.`,
        `//   baseURLString     = ${e.apiUrl}`,
        `//   appId             = ${profile.appId}`,
        `//   xmppWebSocketURL  = ${e.xmppWebSocket}`,
        `//   xmppHost          = ${e.xmppHost}`,
        `//   xmppConference    = ${e.xmppConference}`,
        userLine,
        `// If ethora-sdk-swift is cloned as a sibling, project.yml's EthoraSDK path will also be patched to resolve correctly.`,
      ].join("\n");
    }
    case "wordpress":
      return generateWordPressConfig(profile).content;
    default:
      return generateEnvFile(profile).content;
  }
}
